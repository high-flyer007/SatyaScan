import React from "react";
import { useInspections } from "../context/InspectionContext";
import { useNavigate, useParams } from "react-router-dom";
import {
  ArrowLeft,
  FileText,
  Download,
  CheckCircle2,
  XCircle,
  AlertTriangle,
  ShieldCheck,
  MapPin,
  CalendarDays,
  User,
  Building2,
  Printer,
} from "lucide-react";
import { evaluateCompliance } from "../services/complianceEngine";
import jsPDF from "jspdf";
import html2canvas from "html2canvas";
export default function Report() {
  const navigate = useNavigate();
  const { inspectionId } = useParams();
  const { getInspection } = useInspections();
  const inspection = getInspection(inspectionId || "");
  const complianceResult = React.useMemo(() => {
  if (!inspection) {
    return {
      findings: [],
      passed: 0,
      failed: 0,
      review: 0,
      score: 0,
      overallStatus: "REVIEW_PENDING" as const,
    };
  }

  return {
    findings: evaluateCompliance({
      ...inspection.extractedData,
      ocrText: inspection.ocrText ?? "",
    }).findings,
    passed: inspection.compliance.passed,
    failed: inspection.compliance.failed,
    review: inspection.compliance.review,
    score: inspection.compliance.score,
    overallStatus: inspection.compliance.overallStatus,
  };
}, [inspection]);
  const [generated, setGenerated] = React.useState(false);

  const handleGenerate = async () => {
  const reportElement = document.getElementById("inspection-report");

  if (!reportElement) {
    console.error("SatyaScan: report element not found.");
    return;
  }

  try {
    setGenerated(false);

const canvas = await html2canvas(reportElement, {
  scale: 2,
  useCORS: true,
  backgroundColor: "#ffffff",

  onclone: (clonedDocument) => {
    // Prevent html2canvas from parsing unsupported OKLCH colors.
    clonedDocument.querySelectorAll("style").forEach((style) => {
      style.textContent = style.textContent.replace(
        /oklch\([^)]*\)/gi,
        "#64748b",
      );
    });

    // Replace OKLCH values in inline styles.
    clonedDocument
      .querySelectorAll<HTMLElement>("#inspection-report *")
      .forEach((element) => {
        const inlineStyle = element.getAttribute("style");

        if (inlineStyle?.includes("oklch")) {
          element.setAttribute(
            "style",
            inlineStyle.replace(/oklch\([^)]*\)/gi, "#64748b"),
          );
        }
      });
  },
});

    const imageData = canvas.toDataURL("image/png");

    const pdf = new jsPDF({
      orientation: "portrait",
      unit: "mm",
      format: "a4",
    });

    const pageWidth = pdf.internal.pageSize.getWidth();
    const pageHeight = pdf.internal.pageSize.getHeight();

    const imageWidth = pageWidth;
    const imageHeight =
      (canvas.height * imageWidth) / canvas.width;

    let heightLeft = imageHeight;
    let position = 0;

    pdf.addImage(
      imageData,
      "PNG",
      0,
      position,
      imageWidth,
      imageHeight,
    );

    heightLeft -= pageHeight;

    while (heightLeft > 0) {
      position = heightLeft - imageHeight;

      pdf.addPage();

      pdf.addImage(
        imageData,
        "PNG",
        0,
        position,
        imageWidth,
        imageHeight,
      );

      heightLeft -= pageHeight;
    }

    pdf.save(`SatyaScan-Report-${inspectionId}.pdf`);

    setGenerated(true);
  } catch (error) {
    console.error(
      "SatyaScan: PDF generation failed.",
      error,
    );
  }
};
  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="min-h-screen bg-[#f7f9fc] text-[#102a4c]">
      {/* Header */}
      <header className="border-b border-slate-200 bg-white px-8 py-5">
        <div className="mx-auto flex max-w-[1450px] items-center justify-between">
          <div className="flex items-center gap-4">
            <button
              onClick={() =>
                navigate(`/inspection/${inspectionId}/review`)
              }
              className="rounded-xl border border-slate-200 bg-white p-2.5 transition hover:bg-slate-50"
            >
              <ArrowLeft size={21} />
            </button>

            <div>
              <p className="text-sm font-medium text-slate-500">
                Inspection ID: {inspectionId}
              </p>

              <h1 className="mt-1 text-2xl font-bold">
                Inspection Report
              </h1>

              <p className="mt-1 text-sm text-slate-500">
                Final compliance assessment generated by SatyaScan.
              </p>
            </div>
          </div>

          <div className="flex items-center gap-3">
            <button
              onClick={handlePrint}
              className="inline-flex items-center gap-2 rounded-xl border border-slate-300 bg-white px-5 py-3 font-semibold text-slate-700 transition hover:bg-slate-50"
            >
              <Printer size={18} />
              Print
            </button>

            <button
              onClick={handleGenerate}
              className="inline-flex items-center gap-2 rounded-xl bg-[#0d2b52] px-5 py-3 font-semibold text-white shadow-sm transition hover:bg-[#123b6d]"
            >
              <Download size={18} />
              {generated ? "Report Generated" : "Generate Report"}
            </button>
          </div>
        </div>
      </header>

      <main className="mx-auto max-w-[1250px] px-8 py-8">
        {/* Report document */}
        <div
  id="inspection-report"
  className="overflow-hidden rounded-2xl border border-slate-200 bg-white shadow-sm"
>
          {/* Report header */}
          <div className="border-b border-slate-200 px-8 py-8">
            <div className="flex flex-col justify-between gap-6 md:flex-row md:items-start">
              <div className="flex items-center gap-4">
                <div className="flex h-14 w-14 items-center justify-center rounded-xl bg-[#0d2b52]">
                  <ShieldCheck size={30} className="text-white" />
                </div>

                <div>
                  <h2 className="text-2xl font-bold">
                    <span className="text-[#0d2b52]">
                      Satya
                    </span>
                    <span className="text-emerald-600">
                      Scan
                    </span>
                  </h2>

                  <p className="text-sm text-slate-500">
                    Smart. Connected. Citizen-first.
                  </p>
                </div>
              </div>

              <div className="text-left md:text-right">
                <p className="text-xs font-bold uppercase tracking-wider text-slate-400">
                  Official Inspection Report
                </p>

                <p className="mt-1 text-lg font-bold">
                  {inspectionId}
                </p>

                <p className="text-sm text-slate-500">
                  Generated by SatyaScan
                </p>
              </div>
            </div>
          </div>

          {/* Status */}
<div className="px-8 py-7">
  <div
    className={`rounded-2xl border p-6 ${
      complianceResult.overallStatus === "COMPLIANT"
        ? "border-green-200 bg-green-50"
        : complianceResult.overallStatus === "NON-COMPLIANT"
          ? "border-red-200 bg-red-50"
          : "border-orange-200 bg-orange-50"
    }`}
  >
    <div className="flex flex-col justify-between gap-5 md:flex-row md:items-center">
      <div className="flex items-center gap-4">
        <div
          className={`rounded-xl p-3 ${
            complianceResult.overallStatus === "COMPLIANT"
              ? "bg-green-100"
              : complianceResult.overallStatus === "NON-COMPLIANT"
                ? "bg-red-100"
                : "bg-orange-100"
          }`}
        >
          {complianceResult.overallStatus === "COMPLIANT" ? (
            <CheckCircle2 size={30} className="text-green-600" />
          ) : complianceResult.overallStatus === "NON-COMPLIANT" ? (
            <XCircle size={30} className="text-red-600" />
          ) : (
            <AlertTriangle size={30} className="text-orange-600" />
          )}
        </div>

        <div>
          <p
            className={`text-xs font-bold uppercase tracking-wider ${
              complianceResult.overallStatus === "COMPLIANT"
                ? "text-green-600"
                : complianceResult.overallStatus === "NON-COMPLIANT"
                  ? "text-red-600"
                  : "text-orange-600"
            }`}
          >
            Overall Result
          </p>

          <h2
            className={`mt-1 text-2xl font-bold ${
              complianceResult.overallStatus === "COMPLIANT"
                ? "text-green-700"
                : complianceResult.overallStatus === "NON-COMPLIANT"
                  ? "text-red-700"
                  : "text-orange-700"
            }`}
          >
            {complianceResult.overallStatus === "COMPLIANT"
              ? "COMPLIANT"
              : complianceResult.overallStatus === "NON-COMPLIANT"
                ? "NON-COMPLIANT"
                : "REVIEW PENDING"}
          </h2>

          <p
            className={`mt-1 text-sm ${
              complianceResult.overallStatus === "COMPLIANT"
                ? "text-green-600"
                : complianceResult.overallStatus === "NON-COMPLIANT"
                  ? "text-red-600"
                  : "text-orange-600"
            }`}
          >
            {complianceResult.overallStatus === "COMPLIANT"
              ? "All evaluated declarations passed."
              : complianceResult.overallStatus === "NON-COMPLIANT"
                ? "Compliance action required."
                : "Inspector verification required."}
          </p>
        </div>
      </div>

      <div className="rounded-xl bg-white px-6 py-4 text-center shadow-sm">
        <p className="text-xs font-medium text-slate-500">
          Compliance Score
        </p>

        <p
          className={`mt-1 text-3xl font-bold ${
            complianceResult.overallStatus === "COMPLIANT"
              ? "text-green-600"
              : complianceResult.overallStatus === "NON-COMPLIANT"
                ? "text-red-600"
                : "text-orange-600"
          }`}
        >
          {complianceResult.score}%
        </p>
      </div>
    </div>
  </div>
</div>

          {/* Inspection information */}
          <section className="px-8 pb-7">
            <h3 className="mb-4 text-lg font-bold">
              Inspection Information
            </h3>

            <div className="grid grid-cols-1 gap-4 md:grid-cols-2 lg:grid-cols-4">
             <InfoCard
            icon={<FileText size={18} />}
            label="Inspection ID"
            value={inspection?.id || inspectionId || "Not available"}
            />

              <InfoCard
            icon={<CalendarDays size={18} />}
            label="Inspection Date"
            value={inspection?.date || "Not available"}
            />

            <InfoCard
            icon={<MapPin size={18} />}
            label="Location"
            value={inspection?.location || "Not available"}
            />

            <InfoCard
            icon={<User size={18} />}
            label="Inspector"
            value={inspection?.inspector || "Not available"}
            />
            </div>
          </section>

          {/* Product information */}
          <section className="border-t border-slate-200 px-8 py-7">
            <h3 className="mb-4 text-lg font-bold">
              Product Information
            </h3>

            <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
              <div className="rounded-xl border border-slate-200 p-5">
                <div className="flex items-center gap-3">
                  <div className="rounded-lg bg-blue-50 p-2">
                    <FileText
                      size={19}
                      className="text-blue-700"
                    />
                  </div>

                  <div>
                    <p className="text-xs text-slate-400">
                      PRODUCT
                    </p>

                    <p className="mt-1 font-semibold">
  {inspection?.productName || "Not available"}
</p>
                  </div>
                </div>
              </div>

              <div className="rounded-xl border border-slate-200 p-5">
                <div className="flex items-center gap-3">
                  <div className="rounded-lg bg-purple-50 p-2">
                    <Building2
                      size={19}
                      className="text-purple-700"
                    />
                  </div>

                  <div>
                    <p className="text-xs text-slate-400">
                      MANUFACTURER
                    </p>

                    <p className="mt-1 font-semibold">
  {inspection?.manufacturer || "Not available"}
</p>
                  </div>
                </div>
              </div>
            </div>
          </section>

          {/* Compliance summary */}
          <section className="border-t border-slate-200 px-8 py-7">
            <div className="flex items-center justify-between">
              <div>
                <h3 className="text-lg font-bold">
                  Compliance Summary
                </h3>

                <p className="mt-1 text-sm text-slate-500">
                  Results generated by the SatyaScan rule engine.
                </p>
              </div>

              <span className="rounded-full bg-blue-50 px-4 py-2 text-sm font-semibold text-blue-700">
                4 Rules Evaluated
              </span>
            </div>

            <div className="mt-5 overflow-hidden rounded-xl border border-slate-200">
              <table className="w-full text-left">
                <thead className="bg-slate-50">
                  <tr>
                    <th className="px-5 py-4 text-xs font-bold uppercase tracking-wide text-slate-500">
                      Declaration
                    </th>

                    <th className="px-5 py-4 text-xs font-bold uppercase tracking-wide text-slate-500">
                      Detected Value
                    </th>

                    <th className="px-5 py-4 text-xs font-bold uppercase tracking-wide text-slate-500">
                      Rule
                    </th>

                    <th className="px-5 py-4 text-xs font-bold uppercase tracking-wide text-slate-500">
                      Result
                    </th>
                  </tr>
                </thead>

                <tbody>
  {complianceResult.findings.map((finding) => (
    <tr key={finding.field} className="border-t border-slate-200">
      <td className="px-5 py-4 font-semibold text-slate-800">
        {finding.name}
      </td>

      <td className="px-5 py-4 text-slate-600">
        {finding.value || "Not detected"}
      </td>

      <td className="px-5 py-4 text-blue-600">
        {finding.reference}
      </td>

      <td className="px-5 py-4">
        <span
          className={`inline-flex rounded-full px-3 py-1 text-xs font-semibold ${
            finding.status === "PASS"
              ? "bg-green-50 text-green-700"
              : finding.status === "FAIL"
                ? "bg-red-50 text-red-700"
                : "bg-orange-50 text-orange-700"
          }`}
        >
          {finding.status}
        </span>
      </td>
    </tr>
  ))}
</tbody>
              </table>
            </div>
          </section>

          {/* Violation */}
<section className="border-t border-slate-200 px-8 py-7">
  <h3 className="text-lg font-bold">
    Detected Violations
  </h3>

  {complianceResult.failed > 0 ? (
    <div className="mt-4 space-y-4">
      {complianceResult.findings
        .filter((finding) => finding.status === "FAIL")
        .map((finding) => (
          <div
            key={finding.field}
            className="rounded-xl border border-red-200 bg-red-50 p-5"
          >
            <div className="flex gap-4">
              <div className="rounded-lg bg-red-100 p-2">
                <AlertTriangle
                  size={21}
                  className="text-red-600"
                />
              </div>

              <div>
                <p className="text-sm font-bold text-red-700">
                  {finding.name}
                </p>

                <p className="mt-2 text-sm leading-6 text-slate-600">
                  {finding.description}
                </p>

                <div className="mt-4 flex flex-wrap gap-3">
                  <span className="rounded-lg bg-white px-3 py-2 text-sm font-semibold text-red-700 ring-1 ring-red-200">
                    Severity: {finding.severity}
                  </span>

                  <span className="rounded-lg bg-white px-3 py-2 text-sm font-semibold text-blue-700 ring-1 ring-blue-200">
                    Rule: {finding.reference}
                  </span>
                </div>
              </div>
            </div>
          </div>
        ))}
    </div>
  ) : (
    <div className="mt-4 rounded-xl border border-green-200 bg-green-50 p-5">
      <div className="flex items-center gap-3">
        <CheckCircle2
          size={22}
          className="text-green-600"
        />

        <div>
          <p className="font-semibold text-green-800">
            No violations detected
          </p>

          <p className="mt-1 text-sm text-green-700">
            The automated compliance evaluation found no failed declarations.
          </p>
        </div>
      </div>
    </div>
  )}
</section>
          {/* Inspector verification */}
<section className="border-t border-slate-200 px-8 py-7">
  <h3 className="text-lg font-bold">
    Inspector Verification
  </h3>

  <div
    className={`mt-4 rounded-xl border p-5 ${
      inspection?.confirmed === true
        ? "border-green-200 bg-green-50"
        : inspection?.confirmed === false
          ? "border-slate-200 bg-slate-50"
          : "border-orange-200 bg-orange-50"
    }`}
  >
    <div className="flex items-center gap-3">
      {inspection?.confirmed === true ? (
        <CheckCircle2 size={22} className="text-green-600" />
      ) : inspection?.confirmed === false ? (
        <XCircle size={22} className="text-slate-600" />
      ) : (
        <AlertTriangle size={22} className="text-orange-600" />
      )}

      <div>
        <p
          className={`font-semibold ${
            inspection?.confirmed === true
              ? "text-green-800"
              : inspection?.confirmed === false
                ? "text-slate-800"
                : "text-orange-800"
          }`}
        >
          {inspection?.confirmed === true
            ? "Finding Confirmed"
            : inspection?.confirmed === false
              ? "Finding Rejected"
              : "Verification Pending"}
        </p>

        <p
          className={`mt-1 text-sm ${
            inspection?.confirmed === true
              ? "text-green-700"
              : inspection?.confirmed === false
                ? "text-slate-600"
                : "text-orange-700"
          }`}
        >
          {inspection?.confirmed === true
            ? "The inspector confirmed the inspection finding."
            : inspection?.confirmed === false
              ? "The inspector rejected the automated finding."
              : "The inspection is awaiting final inspector verification."}
        </p>
      </div>
    </div>
  </div>

  {inspection?.inspectorNotes && (
    <div className="mt-4 rounded-xl border border-slate-200 p-5">
      <p className="text-xs font-bold uppercase tracking-wide text-slate-400">
        Inspector Notes
      </p>

      <p className="mt-2 text-sm leading-6 text-slate-600">
        {inspection.inspectorNotes}
      </p>
    </div>
  )}
</section>

          {/* Recommendation */}
<section className="border-t border-slate-200 px-8 py-7">
  <h3 className="text-lg font-bold">
    Recommended Action
  </h3>

  <div
    className={`mt-4 rounded-xl border p-5 ${
      complianceResult.failed > 0
        ? "border-red-200 bg-red-50"
        : complianceResult.review > 0
          ? "border-orange-200 bg-orange-50"
          : "border-green-200 bg-green-50"
    }`}
  >
    {complianceResult.failed > 0 ? (
      <>
        <p className="font-semibold text-red-800">
          Corrective action required
        </p>

        <ul className="mt-3 space-y-2 text-sm text-red-700">
          {complianceResult.findings
            .filter((finding) => finding.status === "FAIL")
            .map((finding) => (
              <li key={finding.field}>
                • Review and correct the {finding.name.toLowerCase()}.
              </li>
            ))}

          <li>
            • Re-inspect the product after corrective action.
          </li>
        </ul>
      </>
    ) : complianceResult.review > 0 ? (
      <>
        <p className="font-semibold text-orange-800">
          Inspector verification required
        </p>

        <ul className="mt-3 space-y-2 text-sm text-orange-700">
          <li>
            • Verify the declarations marked for review against the
            original package image.
          </li>
          <li>
            • Record the inspector's decision and justification.
          </li>
        </ul>
      </>
    ) : (
      <>
        <p className="font-semibold text-green-800">
          No corrective action required
        </p>

        <p className="mt-2 text-sm text-green-700">
          All evaluated declarations passed the automated compliance
          checks. Proceed with final inspector verification.
        </p>
      </>
    )}
  </div>
</section>

          {/* Footer */}
          <div className="border-t border-slate-200 bg-slate-50 px-8 py-6">
            <div className="flex flex-col justify-between gap-3 text-xs text-slate-500 md:flex-row">
              <p>
                Generated by SatyaScan • AI-assisted Legal Metrology
                Inspection Platform
              </p>

              <p>
                Report ID: RPT-{inspectionId || "3525"}
              </p>
            </div>
          </div>
        </div>
      </main>
    </div>
  );
}

/* ---------- Components ---------- */

function InfoCard({
  icon,
  label,
  value,
}: {
  icon: React.ReactNode;
  label: string;
  value: string;
}) {
  return (
    <div className="rounded-xl border border-slate-200 bg-white p-4">
      <div className="flex items-center gap-3">
        <div className="rounded-lg bg-slate-50 p-2 text-slate-600">
          {icon}
        </div>

        <div className="min-w-0">
          <p className="text-xs font-medium text-slate-400">
            {label}
          </p>

          <p className="mt-1 truncate text-sm font-semibold text-slate-800">
            {value}
          </p>
        </div>
      </div>
    </div>
  );
}
